--  SKEMA DATABASE — SISTEM INFORMASI TERINTEGRASI UD. SUMBER URIP (TBSU)
--  Modul: Penjualan & Persediaan   |   Target: Oracle
--  Versi REVISI — konsisten dengan DFD Level 0, IPO, dan SysFlow.
-- =====================================================================
--  RINGKASAN PERUBAHAN vs versi lama:
--   1. SUPPLIER            -> PEMASOK (+ ID_SUPPLIER -> ID_PEMASOK)   [konsistensi diksi]
--   2. MUTASI_PERSEDIAAN   : referensi polimorfik (REFERENSI_TABEL + ID_REFERENSI)
--                            DIGANTI FK eksplisit nullable + CHECK yang bisa ditegakkan DB
--   3. JENIS_MUTASI        : nilai berbasis SEBAB (bukan campur arah); arah ada di QTY_MASUK/KELUAR
--   4. CHECK kondisional baru: void-scope, pengantaran wajib pelanggan, arah mutasi
--   5. Kolom audit DIBUAT_PADA / DIUBAH_PADA di semua tabel
--   6. Waktu-kejadian diseragamkan ke TIMESTAMP
--
--  [CACHE] = kolom nilai turunan (hasil hitung). WAJIB disinkronkan aplikasi/trigger
--            setiap ada transaksi terkait. Sumber kebenaran ada di tabel transaksi/ledger.
-- =====================================================================


-- =========================== MASTER ==================================

CREATE TABLE PENGGUNA (
    ID_PENGGUNA            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAMA_PENGGUNA          VARCHAR2(100 CHAR) NOT NULL,
    USERNAME               VARCHAR2(50 CHAR)  NOT NULL,
    PASSWORD_HASH          VARCHAR2(255 CHAR) NOT NULL,
    ROLE_PENGGUNA          VARCHAR2(20 CHAR)  NOT NULL,
    STATUS_AKTIF           VARCHAR2(10 CHAR)  NOT NULL,
    NO_HP                  VARCHAR2(20 CHAR),
    DIBUAT_PADA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA            TIMESTAMP,
    CONSTRAINT PK_PENGGUNA PRIMARY KEY (ID_PENGGUNA),
    CONSTRAINT UQ_PENGGUNA_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CHK_PENGGUNA_ROLE   CHECK (ROLE_PENGGUNA IN ('OWNER','ADMIN','KASIR','STAF_PENJUALAN')),
    CONSTRAINT CHK_PENGGUNA_STATUS CHECK (STATUS_AKTIF IN ('AKTIF','NONAKTIF'))
);

