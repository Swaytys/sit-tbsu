-- =========================== PENJUALAN ===============================
-- Catatan konsistensi DFD: store "Data Penjualan Langsung" & "Data Penjualan
-- Pengantaran" di DFD = SATU tabel PENJUALAN dgn kolom pembeda JENIS_PENJUALAN.
-- (Memecah jadi 2 tabel fisik = duplikasi struktur, tidak dianjurkan.)

CREATE TABLE PENJUALAN (
    ID_PENJUALAN           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NO_PENJUALAN           VARCHAR2(30 CHAR) NOT NULL,
    TANGGAL_PENJUALAN      TIMESTAMP NOT NULL,
    JENIS_PENJUALAN        VARCHAR2(20 CHAR) NOT NULL,
    ID_ORDER               NUMBER,
    ID_PELANGGAN           NUMBER,
    ID_KASIR               NUMBER NOT NULL,
    TOTAL_BRUTO            NUMBER(19,2) NOT NULL,
    TOTAL_DISKON           NUMBER(19,2) DEFAULT 0 NOT NULL,
    TOTAL_NETO             NUMBER(19,2) NOT NULL,
    METODE_BAYAR_UTAMA     VARCHAR2(20 CHAR) NOT NULL,
    STATUS_PEMBAYARAN      VARCHAR2(20 CHAR) NOT NULL,   -- [CACHE] dari PEMBAYARAN_PENJUALAN
    STATUS_TRANSAKSI       VARCHAR2(20 CHAR) NOT NULL,   -- [CACHE] dari VOID_TRANSAKSI_LOG
    CATATAN_PENJUALAN      VARCHAR2(255 CHAR),
    DIBUAT_PADA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA            TIMESTAMP,
    CONSTRAINT PK_PENJUALAN PRIMARY KEY (ID_PENJUALAN),
    CONSTRAINT UQ_PENJUALAN_NO UNIQUE (NO_PENJUALAN),
    CONSTRAINT FK_PENJUALAN_ORDER     FOREIGN KEY (ID_ORDER)     REFERENCES ORDER_PENJUALAN(ID_ORDER),
    CONSTRAINT FK_PENJUALAN_PELANGGAN FOREIGN KEY (ID_PELANGGAN) REFERENCES PELANGGAN(ID_PELANGGAN),
    CONSTRAINT FK_PENJUALAN_KASIR     FOREIGN KEY (ID_KASIR)     REFERENCES PENGGUNA(ID_PENGGUNA),
    CONSTRAINT CHK_PENJUALAN_JENIS        CHECK (JENIS_PENJUALAN IN ('LANGSUNG','PENGANTARAN')),
    CONSTRAINT CHK_PENJUALAN_METODE       CHECK (METODE_BAYAR_UTAMA IN ('TUNAI','TRANSFER','COD')),
    CONSTRAINT CHK_PENJUALAN_STATUS_BAYAR CHECK (STATUS_PEMBAYARAN IN ('BELUM_LUNAS','DP','LUNAS')),
    CONSTRAINT CHK_PENJUALAN_STATUS       CHECK (STATUS_TRANSAKSI IN ('SELESAI','VOID')),
    -- (4) penjualan pengantaran wajib punya pelanggan (perlu alamat kirim)
    CONSTRAINT CHK_PENJUALAN_PENGANTARAN CHECK (JENIS_PENJUALAN = 'LANGSUNG' OR ID_PELANGGAN IS NOT NULL)
);

CREATE TABLE PENJUALAN_DETAIL (
    ID_PENJUALAN_DETAIL        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PENJUALAN               NUMBER NOT NULL,
    ID_BARANG                  NUMBER NOT NULL,
    QTY_JUAL                   NUMBER(10) NOT NULL,
    HARGA_SATUAN_JUAL          NUMBER(19,2) NOT NULL,   -- snapshot harga jual saat transaksi
    HARGA_MODAL_SAAT_TRANSAKSI NUMBER(19,2) NOT NULL,   -- snapshot HPP saat transaksi (utk laba)
    DISKON_ITEM_JUAL           NUMBER(19,2) DEFAULT 0 NOT NULL,
    SUBTOTAL_JUAL              NUMBER(19,2) NOT NULL,
    STATUS_ITEM                VARCHAR2(20 CHAR) NOT NULL,  -- [CACHE] NORMAL/RETUR/VOID
    DIBUAT_PADA                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA                TIMESTAMP,
    CONSTRAINT PK_PENJUALAN_DETAIL PRIMARY KEY (ID_PENJUALAN_DETAIL),
    CONSTRAINT FK_PENJUALAN_DETAIL_HEADER FOREIGN KEY (ID_PENJUALAN) REFERENCES PENJUALAN(ID_PENJUALAN),
    CONSTRAINT FK_PENJUALAN_DETAIL_BARANG FOREIGN KEY (ID_BARANG)    REFERENCES BARANG(ID_BARANG),
    CONSTRAINT CHK_PENJUALAN_DETAIL_QTY    CHECK (QTY_JUAL > 0),
    CONSTRAINT CHK_PENJUALAN_DETAIL_STATUS CHECK (STATUS_ITEM IN ('NORMAL','RETUR','VOID'))
);

