-- =========================== PERSEDIAAN ==============================
-- Stok terkini per barang. STOK_SAAT_INI = [CACHE] hasil akumulasi MUTASI_PERSEDIAAN.
-- Sumber kebenaran = ledger MUTASI_PERSEDIAAN. Sinkronkan tiap ada mutasi.

CREATE TABLE PERSEDIAAN (
    ID_PERSEDIAAN          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_BARANG              NUMBER NOT NULL,
    STOK_SAAT_INI          NUMBER(10) DEFAULT 0 NOT NULL,   -- [CACHE]
    STOK_TERAKHIR_UPDATE   TIMESTAMP NOT NULL,
    LOKASI_STOK            VARCHAR2(50 CHAR),
    KETERANGAN_STOK        VARCHAR2(150 CHAR),
    DIBUAT_PADA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA            TIMESTAMP,
    CONSTRAINT PK_PERSEDIAAN PRIMARY KEY (ID_PERSEDIAAN),
    CONSTRAINT UQ_PERSEDIAAN_BARANG UNIQUE (ID_BARANG),   -- 1 barang = 1 baris stok
    CONSTRAINT FK_PERSEDIAAN_BARANG FOREIGN KEY (ID_BARANG) REFERENCES BARANG(ID_BARANG),
    CONSTRAINT CHK_PERSEDIAAN_STOK CHECK (STOK_SAAT_INI >= 0)
);


-- =========================== VOID ====================================
-- Dibuat sebelum MUTASI karena MUTASI merujuk ID_VOID.

CREATE TABLE VOID_TRANSAKSI_LOG (
    ID_VOID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PENJUALAN           NUMBER NOT NULL,
    ID_PENJUALAN_DETAIL    NUMBER,               -- diisi hanya bila SCOPE = 'ITEM'
    SCOPE_VOID             VARCHAR2(20 CHAR) NOT NULL,
    TANGGAL_VOID           TIMESTAMP NOT NULL,
    ID_USER_PENGAJU        NUMBER NOT NULL,
    ID_USER_OTORISASI      NUMBER NOT NULL,
    ALASAN_VOID            VARCHAR2(255 CHAR) NOT NULL,
    NOMINAL_VOID           NUMBER(19,2),
    KETERANGAN_VOID        VARCHAR2(150 CHAR),
    DIBUAT_PADA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA            TIMESTAMP,
    CONSTRAINT PK_VOID_TRANSAKSI_LOG PRIMARY KEY (ID_VOID),
    CONSTRAINT FK_VOID_PENJUALAN        FOREIGN KEY (ID_PENJUALAN)        REFERENCES PENJUALAN(ID_PENJUALAN),
    CONSTRAINT FK_VOID_PENJUALAN_DETAIL FOREIGN KEY (ID_PENJUALAN_DETAIL) REFERENCES PENJUALAN_DETAIL(ID_PENJUALAN_DETAIL),
    CONSTRAINT FK_VOID_USER_PENGAJU     FOREIGN KEY (ID_USER_PENGAJU)     REFERENCES PENGGUNA(ID_PENGGUNA),
    CONSTRAINT FK_VOID_USER_OTORISASI   FOREIGN KEY (ID_USER_OTORISASI)   REFERENCES PENGGUNA(ID_PENGGUNA),
    CONSTRAINT CHK_VOID_SCOPE CHECK (SCOPE_VOID IN ('TRANSAKSI','ITEM')),
    -- (4) scope ITEM wajib menyebut baris item; scope TRANSAKSI tidak boleh
    CONSTRAINT CHK_VOID_SCOPE_DETAIL CHECK (
           (SCOPE_VOID = 'ITEM'      AND ID_PENJUALAN_DETAIL IS NOT NULL)
        OR (SCOPE_VOID = 'TRANSAKSI' AND ID_PENJUALAN_DETAIL IS NULL)
    )
);


-- =========================== MUTASI PERSEDIAAN (LEDGER) ==============
-- (2)(3) Referensi polimorfik diganti FK eksplisit nullable.
--        JENIS_MUTASI = SEBAB pergerakan; arah stok ada di QTY_MASUK/QTY_KELUAR.
--        CHECK menjamin: (a) arah sesuai jenis, (b) tepat satu FK sumber terisi
--        sesuai jenis (PENYESUAIAN = semua null; input manual dari stock opname).

CREATE TABLE MUTASI_PERSEDIAAN (
    ID_MUTASI              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_BARANG              NUMBER NOT NULL,
    TANGGAL_MUTASI         TIMESTAMP NOT NULL,
    JENIS_MUTASI           VARCHAR2(20 CHAR) NOT NULL,
    -- FK sumber (tepat satu terisi sesuai JENIS_MUTASI; PENYESUAIAN => semua null)
    ID_PENERIMAAN_DETAIL   NUMBER,
    ID_PENJUALAN_DETAIL    NUMBER,
    ID_RETUR_DETAIL        NUMBER,
    ID_VOID                NUMBER,
    QTY_MASUK              NUMBER(10) DEFAULT 0 NOT NULL,
    QTY_KELUAR             NUMBER(10) DEFAULT 0 NOT NULL,
    SALDO_STOK             NUMBER(10) NOT NULL,   -- saldo stok barang SETELAH mutasi ini
    KETERANGAN_MUTASI      VARCHAR2(255 CHAR),
    DIBUAT_PADA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DIUBAH_PADA            TIMESTAMP,
    CONSTRAINT PK_MUTASI_PERSEDIAAN PRIMARY KEY (ID_MUTASI),
    CONSTRAINT FK_MUTASI_BARANG            FOREIGN KEY (ID_BARANG)            REFERENCES BARANG(ID_BARANG),
    CONSTRAINT FK_MUTASI_PENERIMAAN_DETAIL FOREIGN KEY (ID_PENERIMAAN_DETAIL) REFERENCES PENERIMAAN_BARANG_DETAIL(ID_PENERIMAAN_DETAIL),
    CONSTRAINT FK_MUTASI_PENJUALAN_DETAIL  FOREIGN KEY (ID_PENJUALAN_DETAIL)  REFERENCES PENJUALAN_DETAIL(ID_PENJUALAN_DETAIL),
    CONSTRAINT FK_MUTASI_RETUR_DETAIL      FOREIGN KEY (ID_RETUR_DETAIL)      REFERENCES RETUR_PENJUALAN_DETAIL(ID_RETUR_DETAIL),
    CONSTRAINT FK_MUTASI_VOID              FOREIGN KEY (ID_VOID)              REFERENCES VOID_TRANSAKSI_LOG(ID_VOID),
    CONSTRAINT CHK_MUTASI_JENIS CHECK (JENIS_MUTASI IN ('PENERIMAAN','PENJUALAN','RETUR','VOID','PENYESUAIAN')),
    -- arah stok sesuai sebab (PENERIMAAN/RETUR/VOID = masuk, PENJUALAN = keluar, PENYESUAIAN = salah satu)
    CONSTRAINT CHK_MUTASI_ARAH CHECK (
           (JENIS_MUTASI IN ('PENERIMAAN','RETUR','VOID') AND QTY_MASUK > 0 AND QTY_KELUAR = 0)
        OR (JENIS_MUTASI = 'PENJUALAN'                    AND QTY_KELUAR > 0 AND QTY_MASUK = 0)
        OR (JENIS_MUTASI = 'PENYESUAIAN'                  AND ( (QTY_MASUK > 0 AND QTY_KELUAR = 0)
                                                             OR (QTY_KELUAR > 0 AND QTY_MASUK = 0) ))
    ),
    -- tepat satu FK sumber terisi sesuai jenis
    CONSTRAINT CHK_MUTASI_REF CHECK (
           (JENIS_MUTASI='PENERIMAAN'  AND ID_PENERIMAAN_DETAIL IS NOT NULL AND ID_PENJUALAN_DETAIL IS NULL     AND ID_RETUR_DETAIL IS NULL     AND ID_VOID IS NULL)
        OR (JENIS_MUTASI='PENJUALAN'   AND ID_PENJUALAN_DETAIL IS NOT NULL  AND ID_PENERIMAAN_DETAIL IS NULL    AND ID_RETUR_DETAIL IS NULL     AND ID_VOID IS NULL)
        OR (JENIS_MUTASI='RETUR'       AND ID_RETUR_DETAIL IS NOT NULL      AND ID_PENERIMAAN_DETAIL IS NULL    AND ID_PENJUALAN_DETAIL IS NULL AND ID_VOID IS NULL)
        OR (JENIS_MUTASI='VOID'        AND ID_VOID IS NOT NULL              AND ID_PENERIMAAN_DETAIL IS NULL    AND ID_PENJUALAN_DETAIL IS NULL AND ID_RETUR_DETAIL IS NULL)
        OR (JENIS_MUTASI='PENYESUAIAN' AND ID_PENERIMAAN_DETAIL IS NULL     AND ID_PENJUALAN_DETAIL IS NULL     AND ID_RETUR_DETAIL IS NULL     AND ID_VOID IS NULL)
    ),
    CONSTRAINT CHK_MUTASI_SALDO CHECK (SALDO_STOK >= 0)
);


