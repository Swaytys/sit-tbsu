create index idx_shift_tanggal on shift_kasir(tanggal_operasional);

-- =========================== PENERIMAAN BARANG =======================

create table penerimaan_barang (                                       -- [APPEND]
    id                        bigint generated by default as identity primary key,
    nomor                     varchar(30)  not null unique,     -- RCV-YYMMDD-NNN
    tanggal                   timestamptz  not null default now(),
    tanggal_operasional       date         not null,
    id_pemasok                bigint       not null references pemasok(id),
    id_pengguna               bigint       not null references pengguna(id),
    jenis                     varchar(12)  not null,            -- PEMBELIAN / KONSINYASI
    syarat_bayar              varchar(10),                      -- TUNAI / TEMPO (hanya PEMBELIAN)
    tanggal_jatuh_tempo       date,                             -- wajib bila TEMPO
    no_faktur_pemasok         varchar(50),
    no_surat_jalan_pemasok    varchar(50),
    total_faktur              bigint       not null default 0,  -- [CACHE] sum(subtotal detail); 0 untuk KONSINYASI
    total_dibayar             bigint       not null default 0,  -- [CACHE] sum(pembayaran_pemasok)
    total_retur_potong        bigint       not null default 0,  -- [CACHE] sum(retur_pemasok POTONG_HUTANG) (M2)
    sisa_hutang               bigint       generated always as (total_faktur - total_dibayar - total_retur_potong) stored,
    status_hutang             varchar(12)  not null default 'TIDAK_ADA',  -- [CACHE]
    catatan                   varchar(255),
    dibuat_pada               timestamptz  not null default now(),
    diubah_pada               timestamptz,
    constraint chk_penerimaan_jenis  check (jenis in ('PEMBELIAN','KONSINYASI')),
    constraint chk_penerimaan_syarat check (
           (jenis = 'KONSINYASI' and syarat_bayar is null and tanggal_jatuh_tempo is null)
        or (jenis = 'PEMBELIAN'  and syarat_bayar = 'TUNAI' and tanggal_jatuh_tempo is null)
        or (jenis = 'PEMBELIAN'  and syarat_bayar = 'TEMPO' and tanggal_jatuh_tempo is not null)
    ),
    constraint chk_penerimaan_status_hutang check (status_hutang in ('TIDAK_ADA','BELUM_LUNAS','SEBAGIAN','LUNAS')),
    constraint chk_penerimaan_total check (total_faktur >= 0 and total_dibayar >= 0 and total_retur_potong >= 0
                                           and total_dibayar + total_retur_potong <= total_faktur)
);
create index idx_penerimaan_pemasok on penerimaan_barang(id_pemasok);
create index idx_penerimaan_tanggal on penerimaan_barang(tanggal_operasional);
create index idx_penerimaan_jatuh_tempo on penerimaan_barang(tanggal_jatuh_tempo) where status_hutang in ('BELUM_LUNAS','SEBAGIAN');

create table penerimaan_barang_detail (                                -- [APPEND]
    id                    bigint generated by default as identity primary key,
    id_penerimaan         bigint        not null references penerimaan_barang(id),
    id_barang             bigint        not null references barang(id),
    id_satuan_jual        bigint        references barang_satuan_jual(id),  -- null = satuan dasar (M1 selalu null)
    faktor                numeric(12,4) not null default 1,
    qty_masuk             numeric(14,3) not null,            -- dalam satuan input
    qty_dasar             numeric(14,3) not null,            -- = qty_masuk * faktor
    harga_modal_masuk     bigint        not null,            -- per satuan input
    harga_modal_dasar     bigint        not null,            -- per satuan dasar (dipakai HPP)
    subtotal              bigint        not null,            -- = bulat(qty_masuk * harga_modal_masuk)
    keterangan            varchar(150),
    dibuat_pada           timestamptz   not null default now(),
    constraint chk_penerimaan_detail_qty   check (qty_masuk > 0 and qty_dasar > 0 and faktor > 0),
    constraint chk_penerimaan_detail_harga check (harga_modal_masuk >= 0 and harga_modal_dasar >= 0 and subtotal >= 0)
);
