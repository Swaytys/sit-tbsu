-- =========================== SISTEM ==================================

create table konfigurasi (
    id                bigint generated by default as identity primary key,
    kode              varchar(60)  not null unique,
    nilai             text,
    tipe              varchar(10)  not null default 'TEKS',
    deskripsi         varchar(255),
    dibuat_pada       timestamptz  not null default now(),
    diubah_pada       timestamptz,
    constraint chk_konfigurasi_tipe check (tipe in ('TEKS','ANGKA','BOOL','JSON'))
);
comment on table konfigurasi is 'Profil toko dan setelan sistem (key-value). Dibaca struk, invoice, laporan, aturan bisnis.';

create table penghitung_nomor (
    prefix            varchar(10) not null,
    tanggal_kode      char(6)     not null,          -- YYMMDD
    nilai_terakhir    integer     not null default 0,
    primary key (prefix, tanggal_kode)
);
comment on table penghitung_nomor is 'Penerbit nomor dokumen PREFIX-YYMMDD-NNN. Selalu dibaca dengan SELECT ... FOR UPDATE.';

create table pengguna (
    id                     bigint generated by default as identity primary key,
    kode                   varchar(12)  not null unique,        -- USR-00001
    nama_pengguna          varchar(100) not null,
    username               varchar(50)  not null unique,
    password_hash          varchar(255) not null,
    peran                  varchar(20)  not null,
    status_aktif           varchar(10)  not null default 'AKTIF',
    no_hp                  varchar(20),
    wajib_ganti_password   boolean      not null default false,
    gagal_login_berturut   integer      not null default 0,
    terkunci_sampai        timestamptz,
    login_terakhir         timestamptz,
    dibuat_pada            timestamptz  not null default now(),
    diubah_pada            timestamptz,
    constraint chk_pengguna_peran  check (peran in ('STAF_PENJUALAN','KASIR','ADMIN','OWNER')),
    constraint chk_pengguna_status check (status_aktif in ('AKTIF','NONAKTIF'))
);

create table sesi_login (                                              -- [APPEND]
    id                     bigint generated by default as identity primary key,
    id_pengguna            bigint       not null references pengguna(id),
    token_hash             char(64)     not null unique,               -- sha256(token)
    dibuat_pada            timestamptz  not null default now(),
    kadaluarsa_absolut     timestamptz  not null,
    terakhir_aktif         timestamptz  not null default now(),
    ip                     varchar(45),
    user_agent             varchar(255),
    dicabut_pada           timestamptz,
    alasan_cabut           varchar(50)
);
create index idx_sesi_pengguna on sesi_login(id_pengguna);

create table log_aktivitas (                                           -- [APPEND]
    id                 bigint generated by default as identity primary key,
    waktu              timestamptz  not null default now(),
    id_pengguna        bigint       references pengguna(id),           -- null: login gagal user tak dikenal
    username_percobaan varchar(50),
    aksi               varchar(60)  not null,                          -- mis. PENJUALAN_CHECKOUT, VOID_SETUJUI
    entitas            varchar(40),                                    -- mis. penjualan, barang
    id_entitas         bigint,
    nomor_dokumen      varchar(30),
    ringkasan          text,
    data_lama          jsonb,
    data_baru          jsonb,
    ip                 varchar(45)
);
create index idx_log_waktu    on log_aktivitas(waktu);
create index idx_log_pengguna on log_aktivitas(id_pengguna);
create index idx_log_entitas  on log_aktivitas(entitas, id_entitas);

-- =========================== MASTER ==================================

create table kategori (
    id             bigint generated by default as identity primary key,
    nama           varchar(60)  not null unique,
    keterangan     varchar(150),
    urutan         integer      not null default 0,
    status_aktif   varchar(10)  not null default 'AKTIF',
    dibuat_pada    timestamptz  not null default now(),
    diubah_pada    timestamptz,
    constraint chk_kategori_status check (status_aktif in ('AKTIF','NONAKTIF'))
);

create table satuan (
    id               bigint generated by default as identity primary key,
    kode             varchar(10)  not null unique,        -- m, cm, kg, sak, batang
    nama             varchar(50)  not null,
    jenis_dimensi    varchar(10)  not null,
    faktor_ke_basis  numeric(18,6) not null default 1,    -- cm -> m = 0.01; JUMLAH/LAINNYA selalu 1
    is_basis         boolean      not null default false,
    status_aktif     varchar(10)  not null default 'AKTIF',
    dibuat_pada      timestamptz  not null default now(),
    diubah_pada      timestamptz,
    constraint chk_satuan_dimensi check (jenis_dimensi in ('PANJANG','LUAS','VOLUME','BERAT','DAYA','JUMLAH','LAINNYA')),
    constraint chk_satuan_faktor  check (faktor_ke_basis > 0),
    constraint chk_satuan_status  check (status_aktif in ('AKTIF','NONAKTIF'))
);
-- satu satuan basis per dimensi fisik; JUMLAH/LAINNYA boleh banyak "basis" (tiap satuan hitung berdiri sendiri)
create unique index uq_satuan_basis_dimensi on satuan(jenis_dimensi)
    where is_basis and jenis_dimensi in ('PANJANG','LUAS','VOLUME','BERAT','DAYA');

create table jenis_atribut (
    id             bigint generated by default as identity primary key,
    kode           varchar(30)  not null unique,        -- PANJANG, LEBAR, TEBAL, DIAMETER, BERAT, VOLUME, DAYA, WARNA, ...
    nama           varchar(60)  not null,
    tipe_nilai     varchar(10)  not null,               -- ANGKA / TEKS
    jenis_dimensi  varchar(10),                         -- wajib bila ANGKA berdimensi; null untuk TEKS atau angka tanpa satuan
    urutan         integer      not null default 0,
    status_aktif   varchar(10)  not null default 'AKTIF',
    dibuat_pada    timestamptz  not null default now(),
    diubah_pada    timestamptz,
    constraint chk_jenis_atribut_tipe    check (tipe_nilai in ('ANGKA','TEKS')),
    constraint chk_jenis_atribut_dimensi check (jenis_dimensi is null or jenis_dimensi in ('PANJANG','LUAS','VOLUME','BERAT','DAYA','JUMLAH','LAINNYA')),
    constraint chk_jenis_atribut_teks    check (tipe_nilai = 'ANGKA' or jenis_dimensi is null),
    constraint chk_jenis_atribut_status  check (status_aktif in ('AKTIF','NONAKTIF'))
);

create table pemasok (
    id             bigint generated by default as identity primary key,
    kode           varchar(12)  not null unique,        -- PMS-00001
    nama_pemasok   varchar(100) not null,
    no_hp          varchar(20),
    alamat         varchar(255),
    kontak_person  varchar(100),
    keterangan     varchar(150),
    status_aktif   varchar(10)  not null default 'AKTIF',
    dibuat_pada    timestamptz  not null default now(),
    diubah_pada    timestamptz,
    constraint chk_pemasok_status check (status_aktif in ('AKTIF','NONAKTIF'))
);

create table tingkat_harga (
    id                     bigint generated by default as identity primary key,
    kode                   varchar(20)  not null unique,      -- NORMAL, GROSIR, DISTRIBUTOR
    nama                   varchar(50)  not null,
    markup_default_persen  numeric(6,2) not null default 0,
    saran_min_qty          numeric(14,3),                     -- UI menyorot tier ini bila qty baris >= nilai ini
    urutan                 integer      not null default 0,
    is_default             boolean      not null default false,
    status_aktif           varchar(10)  not null default 'AKTIF',
    dibuat_pada            timestamptz  not null default now(),
    diubah_pada            timestamptz,
    constraint chk_tingkat_harga_status check (status_aktif in ('AKTIF','NONAKTIF'))
);
create unique index uq_tingkat_harga_default on tingkat_harga((1)) where is_default;

create table pelanggan (
    id                bigint generated by default as identity primary key,
    kode              varchar(12)  not null unique,           -- PLG-00001
    nama_pelanggan    varchar(100) not null,
    no_hp             varchar(20),
    email             varchar(100),
    alamat            varchar(255),
    id_tingkat_harga  bigint       references tingkat_harga(id),   -- tier default saat transaksi
    term_hari         integer      not null default 0,             -- jatuh tempo piutang = tanggal + term
    limit_kredit      bigint,                                       -- null = tanpa limit (ditegakkan M2)
    keterangan        varchar(150),
    status_aktif      varchar(10)  not null default 'AKTIF',
    dibuat_pada       timestamptz  not null default now(),
    diubah_pada       timestamptz,
    constraint chk_pelanggan_status check (status_aktif in ('AKTIF','NONAKTIF')),
    constraint chk_pelanggan_term   check (term_hari >= 0),
    constraint chk_pelanggan_limit  check (limit_kredit is null or limit_kredit >= 0)
);
create index idx_pelanggan_nama on pelanggan(nama_pelanggan);
create index idx_pelanggan_hp   on pelanggan(no_hp);

create table barang (
    id                       bigint generated by default as identity primary key,
    kode                     varchar(12)  not null unique,     -- BRG-00001
    barcode                  varchar(64)  unique,
    nama_barang              varchar(150) not null,
    id_kategori              bigint       not null references kategori(id),
    merk                     varchar(50),
    id_satuan_dasar          bigint       not null references satuan(id),   -- satuan tempat stok dicatat
    stok_minimum             numeric(14,3) not null default 0,
    harga_modal_awal         bigint       not null default 0,  -- dasar HPP & markup sebelum ada penerimaan
    kepemilikan              varchar(15)  not null default 'MILIK_SENDIRI',
    id_pemasok_konsinyasi    bigint       references pemasok(id),
    harga_titip              bigint,                           -- per satuan dasar, hanya KONSINYASI
    harga_otomatis           boolean      not null default false,   -- true: harga jual mengikuti markup tanpa tinjau (M2)
    perlu_tinjau_harga       boolean      not null default false,   -- diset saat dasar markup berubah (M2)
    gambar                   varchar(255),
    keterangan               varchar(255),
    status_aktif             varchar(10)  not null default 'AKTIF',
    dibuat_pada              timestamptz  not null default now(),
    diubah_pada              timestamptz,
    constraint chk_barang_status      check (status_aktif in ('AKTIF','NONAKTIF')),
    constraint chk_barang_kepemilikan check (kepemilikan in ('MILIK_SENDIRI','KONSINYASI')),
    constraint chk_barang_konsinyasi  check (
           (kepemilikan = 'MILIK_SENDIRI' and id_pemasok_konsinyasi is null and harga_titip is null)
        or (kepemilikan = 'KONSINYASI'    and id_pemasok_konsinyasi is not null and harga_titip is not null and harga_titip >= 0)
    ),
    constraint chk_barang_stok_min    check (stok_minimum >= 0),
    constraint chk_barang_modal_awal  check (harga_modal_awal >= 0)
);
create index idx_barang_nama     on barang(nama_barang);
create index idx_barang_kategori on barang(id_kategori);

create table barang_atribut (
    id                 bigint generated by default as identity primary key,
    id_barang          bigint        not null references barang(id),
    id_jenis_atribut   bigint        not null references jenis_atribut(id),
    nilai_angka        numeric(18,4),
    id_satuan          bigint        references satuan(id),
    nilai_teks         varchar(150),
    urutan             integer       not null default 0,
    constraint uq_barang_atribut unique (id_barang, id_jenis_atribut),
    constraint chk_barang_atribut_nilai check (num_nonnulls(nilai_angka, nilai_teks) = 1)
);

create table barang_satuan_jual (
    id                bigint generated by default as identity primary key,
    id_barang         bigint        not null references barang(id),
    id_satuan         bigint        not null references satuan(id),
    faktor_ke_dasar   numeric(12,4) not null,          -- 1 roll = 50 m  -> 50
    barcode           varchar(64)   unique,
    is_default_jual   boolean       not null default false,
    status_aktif      varchar(10)   not null default 'AKTIF',
    dibuat_pada       timestamptz   not null default now(),
    diubah_pada       timestamptz,
    constraint uq_barang_satuan_jual unique (id_barang, id_satuan),
    constraint chk_bsj_faktor check (faktor_ke_dasar > 0),
    constraint chk_bsj_status check (status_aktif in ('AKTIF','NONAKTIF'))
);

create table harga_barang (
    id                 bigint generated by default as identity primary key,
    id_barang          bigint       not null references barang(id),
    id_tingkat_harga   bigint       not null references tingkat_harga(id),
    id_satuan_jual     bigint       references barang_satuan_jual(id),   -- null = per satuan dasar
    metode             varchar(10)  not null default 'TETAP',          -- IKUT_TIER / MARKUP / TETAP
    markup_persen      numeric(6,2),                                   -- hanya MARKUP
    harga_tetap        bigint,                                         -- hanya TETAP
    harga_jual         bigint       not null,                          -- harga berlaku, disimpan (K-010)
    dasar_markup_saat_hitung bigint,                                   -- nilai dasar saat harga_jual dihitung (untuk tinjau)
    id_pengguna        bigint       references pengguna(id),
    dibuat_pada        timestamptz  not null default now(),
    diubah_pada        timestamptz,
    constraint uq_harga_barang unique nulls not distinct (id_barang, id_tingkat_harga, id_satuan_jual),
    constraint chk_harga_metode check (metode in ('IKUT_TIER','MARKUP','TETAP')),
    constraint chk_harga_isi check (
           (metode = 'IKUT_TIER' and markup_persen is null and harga_tetap is null)
        or (metode = 'MARKUP'    and markup_persen is not null and harga_tetap is null)
        or (metode = 'TETAP'     and harga_tetap is not null)
    ),
    constraint chk_harga_jual check (harga_jual >= 0)
);
create index idx_harga_barang_barang on harga_barang(id_barang);

create table promo (                                                   -- M2
    id                 bigint generated by default as identity primary key,
    kode               varchar(20)  not null unique,
    nama               varchar(100) not null,
    tanggal_mulai      date         not null,
    tanggal_selesai    date         not null,
    jenis_potongan     varchar(10)  not null,      -- PERSEN / NOMINAL
    potongan_persen    numeric(6,2),
    potongan_nominal   bigint,
    maks_potongan      bigint,                     -- batas Rp untuk PERSEN, opsional
    sasaran            varchar(10)  not null,      -- SEMUA / KATEGORI / BARANG
    id_kategori        bigint       references kategori(id),
    id_barang          bigint       references barang(id),
    min_qty            numeric(14,3),
    min_belanja        bigint,
    keterangan         varchar(255),
    status_aktif       varchar(10)  not null default 'AKTIF',
    dibuat_pada        timestamptz  not null default now(),
    diubah_pada        timestamptz,
    constraint chk_promo_tanggal  check (tanggal_selesai >= tanggal_mulai),
    constraint chk_promo_jenis    check (jenis_potongan in ('PERSEN','NOMINAL')),
    constraint chk_promo_nilai    check (
           (jenis_potongan = 'PERSEN'  and potongan_persen  is not null and potongan_persen between 0 and 100 and potongan_nominal is null)
        or (jenis_potongan = 'NOMINAL' and potongan_nominal is not null and potongan_nominal >= 0 and potongan_persen is null)
    ),
    constraint chk_promo_sasaran  check (
           (sasaran = 'SEMUA'    and id_kategori is null     and id_barang is null)
        or (sasaran = 'KATEGORI' and id_kategori is not null and id_barang is null)
        or (sasaran = 'BARANG'   and id_barang   is not null and id_kategori is null)
    ),
    constraint chk_promo_status   check (status_aktif in ('AKTIF','NONAKTIF'))
);

-- =========================== PERSEDIAAN (POSISI) =====================

create table persediaan (
    id                    bigint generated by default as identity primary key,
    id_barang             bigint        not null unique references barang(id),
    stok_fisik            numeric(14,3) not null default 0,   -- [CACHE] dari ledger, kondisi BAIK
    stok_dipesan          numeric(14,3) not null default 0,   -- [CACHE] dari order MENUNGGU/DIPROSES
    stok_tersedia         numeric(14,3) generated always as (stok_fisik - stok_dipesan) stored,
    stok_rusak            numeric(14,3) not null default 0,   -- [CACHE] dari ledger, kondisi RUSAK (M2)
    hpp_rata2             bigint        not null default 0,   -- [CACHE] rata-rata tertimbang, per satuan dasar
    harga_beli_terakhir   bigint        not null default 0,   -- [CACHE] dari penerimaan PEMBELIAN terakhir
    tanggal_beli_terakhir date,
    lokasi_stok           varchar(50),
    keterangan            varchar(150),
    terakhir_mutasi       timestamptz,
    dibuat_pada           timestamptz   not null default now(),
    diubah_pada           timestamptz,
    constraint chk_persediaan_fisik   check (stok_fisik >= 0),
    constraint chk_persediaan_dipesan check (stok_dipesan >= 0 and stok_dipesan <= stok_fisik),
    constraint chk_persediaan_rusak   check (stok_rusak >= 0),
    constraint chk_persediaan_hpp     check (hpp_rata2 >= 0 and harga_beli_terakhir >= 0)
);

