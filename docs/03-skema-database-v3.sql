--  Target: PostgreSQL 15+  (memakai UNIQUE NULLS NOT DISTINCT, generated columns, num_nonnulls)
--  Berkas ini menjadi migrasi 0000. Perubahan berikutnya lewat migrasi baru, tidak mengedit berkas ini.
