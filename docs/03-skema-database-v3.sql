create table penjualan (                                               -- [APPEND] kecuali status & cache
    id                     bigint generated by default as identity primary key,
    nomor                  varchar(30)  not null unique,      -- STR-YYMMDD-NNN (langsung) / INV-YYMMDD-NNN (pengantaran)
    tanggal                timestamptz  not null default now(),
    tanggal_operasional    date         not null,
    jenis_penjualan        varchar(12)  not null,
    id_order               bigint       references order_penjualan(id),
    id_pelanggan           bigint       references pelanggan(id),
    nama_pembeli           varchar(100),
    id_kasir               bigint       not null references pengguna(id),
    id_shift               bigint       references shift_kasir(id),   -- shift kasir saat checkout (null: checkout non-tunai tanpa shift)
    total_bruto            bigint       not null,             -- sum(qty * harga_satuan)
    total_diskon           bigint       not null default 0,  -- sum(diskon_baris + diskon_promo) + diskon_transaksi
    diskon_transaksi       bigint       not null default 0,
    ongkir                 bigint       not null default 0,
    total_neto             bigint       not null,             -- bruto - total_diskon + ongkir
    total_void             bigint       not null default 0,  -- [CACHE] sum(void_transaksi.nominal_void DISETUJUI): nilai barang yang dibatalkan
    total_retur            bigint       not null default 0,  -- [CACHE] sum(retur DISETUJUI dgn penyelesaian REFUND/POTONG_TAGIHAN): nilai barang dikembalikan
    total_dibayar          bigint       not null default 0,  -- [CACHE] sum(pembayaran_penjualan.nominal)
    total_refund           bigint       not null default 0,  -- [CACHE] uang yang dikembalikan ke pembeli (retur REFUND + void)
    -- tagihan = neto - void - retur ; dibayar bersih = dibayar - refund ; sisa = tagihan - dibayar bersih
    sisa_tagihan           bigint       generated always as (total_neto - total_void - total_retur - total_dibayar + total_refund) stored,
    status_pembayaran      varchar(12)  not null default 'BELUM_BAYAR',   -- [CACHE] BELUM_BAYAR / DP / LUNAS
    bayar_saat_terima      boolean      not null default false,           -- "COD"
    tanggal_jatuh_tempo    date,
    status_transaksi       varchar(15)  not null default 'SELESAI',       -- [CACHE] SELESAI / VOID_SEBAGIAN / VOID
    status_pengambilan     varchar(15),                       -- LANGSUNG: DIAMBIL / BELUM_DIAMBIL
    status_pengiriman      varchar(10),                       -- PENGANTARAN: BELUM / SEBAGIAN / SELESAI  [CACHE] dari surat_jalan
    alamat_kirim           varchar(255),
    catatan_kirim          varchar(255),
    catatan                varchar(255),
    dibuat_pada            timestamptz  not null default now(),
    diubah_pada            timestamptz,
    constraint chk_penjualan_jenis   check (jenis_penjualan in ('LANGSUNG','PENGANTARAN')),
    constraint chk_penjualan_bayar   check (status_pembayaran in ('BELUM_BAYAR','DP','LUNAS')),
    constraint chk_penjualan_status  check (status_transaksi in ('SELESAI','VOID_SEBAGIAN','VOID')),
    constraint chk_penjualan_langsung check (
           (jenis_penjualan = 'LANGSUNG'    and status_pengambilan in ('DIAMBIL','BELUM_DIAMBIL') and status_pengiriman is null)
        or (jenis_penjualan = 'PENGANTARAN' and status_pengiriman in ('BELUM','SEBAGIAN','SELESAI') and status_pengambilan is null
            and id_pelanggan is not null and alamat_kirim is not null)
    ),
    constraint chk_penjualan_uang check (total_bruto >= 0 and total_diskon >= 0 and diskon_transaksi >= 0 and ongkir >= 0
                                         and total_neto >= 0 and total_dibayar >= 0 and total_void >= 0 and total_retur >= 0
                                         and total_refund >= 0 and total_void + total_retur <= total_neto and total_refund <= total_dibayar)
);
create index idx_penjualan_tanggal   on penjualan(tanggal_operasional);
create index idx_penjualan_pelanggan on penjualan(id_pelanggan);
create index idx_penjualan_kasir     on penjualan(id_kasir);
create index idx_penjualan_shift     on penjualan(id_shift);
create index idx_penjualan_order     on penjualan(id_order);
create index idx_penjualan_piutang   on penjualan(tanggal_jatuh_tempo) where status_pembayaran <> 'LUNAS' and status_transaksi <> 'VOID';

