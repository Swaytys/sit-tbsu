--  Konvensi:
--   - nama tabel/kolom snake_case huruf kecil, istilah mengikuti Laporan KP
--   - uang  = bigint (rupiah utuh)         qty = numeric(14,3)        persen = numeric(6,2)
--   - waktu = timestamptz (UTC)            tanggal_operasional = date (tanggal lokal Asia/Jakarta)
--   - [CACHE]  = kolom hasil hitung; sumber kebenaran di tabel transaksi/ledger; disinkronkan
--                aplikasi di transaksi DB yang sama (lihat docs/03 §4)
--   - [APPEND] = tabel append-only: tidak ada UPDATE isi / DELETE, kecuali kolom status & cache
--   - enum status ditegakkan CHECK; daftar nilai = packages/shared/src/enums.ts
