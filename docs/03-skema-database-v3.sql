-- =========================== MUTASI PERSEDIAAN (LEDGER) ==============
-- Sumber kebenaran stok. Setiap baris = satu pergerakan satu bucket (BAIK/RUSAK) satu barang.
-- Ditulis HANYA oleh modules/persediaan/ledger.ts (CLAUDE.md aturan 2).

create table mutasi_persediaan (                                       -- [APPEND]
    id                        bigint generated by default as identity primary key,
    id_barang                 bigint        not null references barang(id),
    waktu                     timestamptz   not null default now(),
    tanggal_operasional       date          not null,
    jenis_mutasi              varchar(15)   not null,
    kondisi                   varchar(6)    not null default 'BAIK',   -- bucket: BAIK / RUSAK
    qty_masuk                 numeric(14,3) not null default 0,
    qty_keluar                numeric(14,3) not null default 0,
    saldo_setelah             numeric(14,3) not null,         -- saldo bucket ini SETELAH mutasi
    hpp_satuan                bigint        not null default 0,   -- nilai per satuan dasar yang bergerak
    hpp_setelah               bigint        not null default 0,   -- hpp_rata2 barang setelah mutasi (bucket BAIK)
    id_penerimaan_detail      bigint        references penerimaan_barang_detail(id),
    id_penjualan_detail       bigint        references penjualan_detail(id),
    id_retur_detail           bigint        references retur_penjualan_detail(id),
    id_void_detail            bigint        references void_transaksi_detail(id),
    id_penyesuaian_detail     bigint        references penyesuaian_stok_detail(id),
    id_retur_pemasok_detail   bigint        references retur_pemasok_detail(id),
    id_pengguna               bigint        not null references pengguna(id),
    keterangan                varchar(255),
    dibuat_pada               timestamptz   not null default now(),
    constraint chk_mutasi_jenis check (jenis_mutasi in
        ('SALDO_AWAL','PENERIMAAN','PENJUALAN','RETUR_JUAL','TUKAR_RETUR','VOID','PENYESUAIAN','PINDAH_KONDISI','RETUR_PEMASOK','MUSNAH')),
    constraint chk_mutasi_kondisi check (kondisi in ('BAIK','RUSAK')),
    constraint chk_mutasi_qty   check (qty_masuk >= 0 and qty_keluar >= 0 and saldo_setelah >= 0 and hpp_satuan >= 0 and hpp_setelah >= 0),
    -- arah sesuai sebab
    constraint chk_mutasi_arah check (
           (jenis_mutasi in ('SALDO_AWAL','PENERIMAAN','RETUR_JUAL','VOID')            and qty_masuk  > 0 and qty_keluar = 0)
        or (jenis_mutasi in ('PENJUALAN','TUKAR_RETUR','RETUR_PEMASOK','MUSNAH')       and qty_keluar > 0 and qty_masuk  = 0)
        or (jenis_mutasi in ('PENYESUAIAN','PINDAH_KONDISI') and ((qty_masuk > 0 and qty_keluar = 0) or (qty_keluar > 0 and qty_masuk = 0)))
    ),
    -- tepat satu referensi sumber, sesuai jenis
    constraint chk_mutasi_ref check (
        num_nonnulls(id_penerimaan_detail, id_penjualan_detail, id_retur_detail, id_void_detail, id_penyesuaian_detail, id_retur_pemasok_detail) = 1
        and (jenis_mutasi <> 'PENERIMAAN'                                   or id_penerimaan_detail    is not null)
        and (jenis_mutasi <> 'PENJUALAN'                                    or id_penjualan_detail     is not null)
        and (jenis_mutasi not in ('RETUR_JUAL','TUKAR_RETUR')                or id_retur_detail         is not null)
        and (jenis_mutasi <> 'VOID'                                         or id_void_detail          is not null)
        and (jenis_mutasi not in ('SALDO_AWAL','PENYESUAIAN','PINDAH_KONDISI','MUSNAH') or id_penyesuaian_detail is not null)
        and (jenis_mutasi <> 'RETUR_PEMASOK'                                or id_retur_pemasok_detail is not null)
    ),
    constraint chk_mutasi_musnah check (jenis_mutasi <> 'MUSNAH' or kondisi = 'RUSAK')
);
create index idx_mutasi_barang_waktu on mutasi_persediaan(id_barang, waktu);
create index idx_mutasi_tanggal      on mutasi_persediaan(tanggal_operasional);
create index idx_mutasi_penerimaan   on mutasi_persediaan(id_penerimaan_detail);
create index idx_mutasi_penjualan    on mutasi_persediaan(id_penjualan_detail);
create index idx_mutasi_retur        on mutasi_persediaan(id_retur_detail);
create index idx_mutasi_void         on mutasi_persediaan(id_void_detail);
create index idx_mutasi_penyesuaian  on mutasi_persediaan(id_penyesuaian_detail);
create index idx_mutasi_retur_pemasok on mutasi_persediaan(id_retur_pemasok_detail);

